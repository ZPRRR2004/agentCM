// Background browser acceptance for result scopes, identical imports and independent flags.
const { chromium } = require('playwright');
const { spawn } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const fixture = spawn(process.env.PYTHON_BIN || 'python3', [path.join(__dirname, 'browser_fixture.py'), '--selection'], { cwd: root, stdio: ['ignore', 'pipe', 'inherit'] });
let browser;
async function run() {
  const url = await new Promise((resolve, reject) => {
    let output = '';
    fixture.stdout.on('data', data => { output += data; if (output.includes('\n')) resolve(JSON.parse(output.split('\n')[0]).url); });
    fixture.on('exit', code => reject(new Error('Fixture exited ' + code)));
  });
  browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url + '/#experiments');
  await page.getByRole('button', { name: '新建实验', exact: true }).click();
  await page.locator('[data-action=new-preprocess]').click();
  await page.locator('#new-preprocess-form [name=title]').fill('成功与失败 · 保留独立尝试');
  assert.equal(await page.locator('#preprocess-result-scope').inputValue(), 'all');
  await page.locator('#preprocess-selection-preview .selection-counts').getByText('输入 7 条 → 保留 4 条 · 排除 3 条', { exact: true }).waitFor();
  assert((await page.locator('.selection-outcomes').textContent()).includes('任务失败 2 条'));
  assert((await page.locator('#preprocess-selection-preview').textContent()).includes('无工具调用 1 条'));
  await page.locator('#new-preprocess-form .split-inputs summary').click();
  await page.getByRole('button', { name: '全不选', exact: true }).click();
  await page.locator('#preprocess-picker [value=unscored]').check();
  await page.locator('#preprocess-selection-preview .selection-counts').getByText('输入 1 条 → 保留 0 条 · 排除 1 条', { exact: true }).waitFor();
  assert.equal(await page.locator('[form=new-preprocess-form][type=submit]').isDisabled(), true);
  await page.getByRole('button', { name: '全不选', exact: true }).click();
  await page.locator('#preprocess-picker [value=empty-content]').check();
  await page.locator('#preprocess-selection-preview .selection-counts').getByText('输入 1 条 → 保留 0 条 · 排除 1 条', { exact: true }).waitFor();
  assert.equal(await page.locator('[form=new-preprocess-form][type=submit]').isDisabled(), true);
  assert((await page.locator('#preprocess-selection-preview').textContent()).includes('没有可建模的内容'));
  await page.getByRole('button', { name: '全不选', exact: true }).click();
  await page.locator('#preprocess-picker [value=failed-no-tools]').check();
  await page.locator('#preprocess-selection-preview .selection-counts').getByText('输入 1 条 → 保留 1 条 · 排除 0 条', { exact: true }).waitFor();
  assert.equal(await page.locator('[form=new-preprocess-form][type=submit]').isDisabled(), false);
  assert((await page.locator('#preprocess-selection-preview').textContent()).includes('保留含 reasoning 内容的轨迹'));
  await page.getByRole('button', { name: '全不选', exact: true }).click();
  await page.locator('#preprocess-picker [value=failed-last]').check();
  await page.locator('#preprocess-selection-preview .selection-counts').getByText('输入 1 条 → 保留 1 条 · 排除 0 条', { exact: true }).waitFor();
  assert.equal(await page.locator('[form=new-preprocess-form][type=submit]').isDisabled(), false);
  await page.locator('#preprocess-result-scope').selectOption('success_only');
  await page.getByText('当前结果条件下没有可处理轨迹，请调整轨迹选择或结果范围。', { exact: true }).waitFor();
  assert.equal(await page.locator('[form=new-preprocess-form][type=submit]').isDisabled(), true);
  await page.getByRole('checkbox', { name: '全选轨迹', exact: true }).check();
  await page.locator('#preprocess-selection-preview .selection-counts').getByText('输入 7 条 → 保留 2 条 · 排除 5 条', { exact: true }).waitFor();
  await page.locator('#preprocess-result-scope').selectOption('all');
  await page.locator('#preprocess-selection-preview .selection-counts').getByText('输入 7 条 → 保留 4 条 · 排除 3 条', { exact: true }).waitFor();
  await page.locator('#preprocess-selection-preview details summary').click();
  assert.equal(await page.locator('#preprocess-selection-preview tbody tr').count(), 7);
  const flagged = page.locator('#preprocess-selection-preview [data-trajectory-id=unscored]');
  assert.equal(await flagged.locator('[data-trajectory-flag]').count(), 2);
  assert((await flagged.textContent()).includes('环境 / 运行器故障导致执行中断'));
  assert((await flagged.textContent()).includes('排除'));
  const noTools = page.locator('#preprocess-selection-preview [data-trajectory-id=failed-no-tools]');
  assert((await noTools.textContent()).includes('保留含 reasoning 内容的轨迹'));
  assert((await noTools.textContent()).includes('保留'));
  assert((await noTools.textContent()).includes('个 reasoning'));
  assert.equal(await page.locator('#preprocess-picker label').filter({ has: page.locator('[value=unscored]') }).locator('[data-trajectory-flag]').count(), 2);
  const output = path.join(root, 'runs', 'browser-checks'); fs.mkdirSync(output, { recursive: true });
  await page.locator('#preprocess-selection-preview').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(output, 'preprocess-selection-create.png') });
  await page.getByRole('button', { name: '创建预处理实验草稿', exact: true }).click();
  await page.locator('#preprocess-after').waitFor();
  assert.deepEqual(await page.locator('#preprocess-trajectory option').evaluateAll(options => options.map(o => o.value)), ['failed-last', 'failed-no-tools', 'success-retry', 'test-trajectory']);
  assert((await page.locator('.preprocess-selection').textContent()).includes('重复导入 1 条'));
  assert((await page.locator('.preprocess-selection').textContent()).includes('环境故障中断 1 条'));
  assert((await page.locator('.preprocess-selection').textContent()).includes('无工具调用 1 条'));
  await page.locator('#preprocess-trajectory').selectOption('failed-last');
  assert.equal(await page.locator('.preprocess-assessment [data-trajectory-flag]').count(), 0);
  await page.getByRole('button', { name: '开始运行', exact: true }).click();
  await page.getByRole('button', { name: '基于此结果创建切分', exact: true }).waitFor();
  await page.reload();
  await page.locator('#preprocess-after').waitFor();
  await page.locator('.preprocess-selection details summary').click();
  await page.screenshot({ path: path.join(output, 'preprocess-selection-detail.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.preprocess-selection').scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: path.join(output, 'preprocess-selection-mobile.png') });
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.getByRole('button', { name: '基于此结果创建切分', exact: true }).click();
  await page.locator('#split-trajectory-picker input').first().waitFor({ state: 'attached' });
  assert.equal(await page.locator('#split-trajectory-picker input').count(), 4);
  assert.deepEqual(await page.locator('#split-trajectory-picker input').evaluateAll(inputs => inputs.map(i => i.value)), ['failed-last', 'failed-no-tools', 'success-retry', 'test-trajectory']);
  assert.deepEqual(errors, []);
  console.log('PASS reasoning-only retention, infrastructure/empty exclusion, result scopes, exact duplicates, frozen review, downstream inputs and responsive layout');
}
run().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); fixture.kill('SIGTERM'); });
