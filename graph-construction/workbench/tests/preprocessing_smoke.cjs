// Isolated browser checks of preprocessing review and downstream splitting.
const { chromium } = require('playwright');
const { spawn } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const fixture = spawn(process.env.PYTHON_BIN || 'python3', [path.join(__dirname, 'browser_fixture.py'), '--preprocess'], { cwd: root, stdio: ['ignore', 'pipe', 'inherit'] });
let browser;
async function run() {
  const url = await new Promise((resolve, reject) => {
    let output = '';
    fixture.stdout.on('data', data => { output += data; if (output.includes('\n')) resolve(JSON.parse(output.split('\n')[0]).url); });
    fixture.on('exit', code => reject(new Error('Fixture exited ' + code)));
  });
  browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(url + '/#experiments');
  await page.getByRole('button', { name: '新建实验', exact: true }).click();
  assert.equal(await page.locator('.experiment-kind').count(), 3);
  await page.locator('[data-action=new-preprocess]').click();
  await page.locator('#new-preprocess-form [name=title]').fill('工具输出去重 · 对照实验');
  await page.locator('[name=remove_source_lines]').check();
  assert.equal(await page.locator('[name=simplify_call_ids]').isChecked(), false);
  await page.getByRole('checkbox', { name: '精简调用标识', exact: false }).check();
  await page.locator('#new-preprocess-form .split-inputs summary').click();
  const selectAll = page.getByRole('checkbox', { name: '全选轨迹', exact: true });
  await selectAll.uncheck();
  assert.equal(await page.locator('#preprocess-picker input:checked').count(), 0);
  await page.getByRole('button', { name: '创建预处理实验草稿', exact: true }).click();
  await page.locator('#modal-error').getByText('请至少选择一条轨迹', { exact: true }).waitFor();
  await selectAll.check();
  await page.getByRole('button', { name: '全不选', exact: true }).click();
  await page.locator('#preprocess-picker input').first().check();
  assert.equal(await page.locator('#preprocess-selection-count').textContent(), '已选 1 / 1 条轨迹');
  await page.getByRole('button', { name: '创建预处理实验草稿', exact: true }).click();
  await page.locator('#preprocess-after').waitFor();
  const before = JSON.parse(await page.locator('#preprocess-before').textContent());
  const after = JSON.parse(await page.locator('#preprocess-after').textContent());
  assert('source_line' in before);
  assert(!('source_line' in after));
  assert('content' in before.tool_calls[0].observation);
  assert(!('content' in after.tool_calls[0].observation));
  assert.equal(before.tool_calls[0].observation.raw, after.tool_calls[0].observation.raw);
  assert.equal(after.tool_calls[0].tool_call_id, 'call-0001');
  assert(!('source_call_id' in after.tool_calls[0]));
  const marks = page.locator('#preprocess-before .preprocess-removed');
  assert.equal(await marks.count(), 4);
  assert.equal(await page.locator('#preprocess-after .preprocess-removed').count(), 0);
  assert.equal(await page.locator('#preprocess-before').textContent(), JSON.stringify(before, null, 2));
  assert.equal(await page.locator('#preprocess-after').textContent(), JSON.stringify(after, null, 2));
  for (const side of ['before', 'after']) {
    const replaced = page.locator(`#preprocess-${side} .preprocess-replaced`);
    assert.equal(await replaced.count(), 1);
    assert.equal(await replaced.getAttribute('data-replaced-path'), 'events[0].tool_calls[0].tool_call_id');
    assert((await replaced.getAttribute('title')).includes(before.tool_calls[0].tool_call_id));
    assert((await replaced.getAttribute('title')).includes('call-0001'));
    assert.equal(await replaced.evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(255, 240, 179)');
  }
  const contentMark = page.locator('#preprocess-before [data-removed-path="events[0].tool_calls[0].observation.content"]');
  assert((await contentMark.textContent()).includes('"content": ['));
  assert((await contentMark.textContent()).includes('<script>sample</script>'));
  assert.equal(await contentMark.locator('script').count(), 0);
  assert.equal(await contentMark.evaluate(el => getComputedStyle(el).color), 'rgb(165, 43, 39)');
  const experimentUrl = page.url();
  await page.getByRole('button', { name: '开始运行', exact: true }).click();
  await page.getByRole('button', { name: '基于此结果创建切分', exact: true }).waitFor();
  await page.locator('#preprocess-after').waitFor();
  await page.reload();
  await page.locator('#preprocess-after').waitFor();
  assert.deepEqual(JSON.parse(await page.locator('#preprocess-after').textContent()), after);
  await page.locator('.preprocess-id-mapping summary').click();
  assert((await page.locator('.preprocess-id-mapping tbody').textContent()).includes(before.tool_calls[0].source_call_id));
  assert.equal(await page.locator('.preprocess-id-mapping tbody tr').count(), 1);
  await page.locator('#preprocess-event').selectOption('__all__');
  await page.waitForFunction(() => JSON.parse(document.querySelector('#preprocess-after').textContent).events?.length === 3);
  assert.equal(await page.locator('#preprocess-before .preprocess-removed').count(), 12);
  assert.equal(await page.locator('#preprocess-before .preprocess-replaced').count(), 3);
  assert.equal(await page.locator('#preprocess-after .preprocess-replaced').count(), 3);
  assert.equal(await page.locator('.preprocess-id-mapping tbody tr').count(), 3);
  const fullBefore = await page.locator('#preprocess-before').textContent();
  assert.equal(fullBefore, JSON.stringify(JSON.parse(fullBefore), null, 2));
  await page.locator('#preprocess-event').selectOption('event-2');
  await page.waitForFunction(() => JSON.parse(document.querySelector('#preprocess-after').textContent).event_id === 'event-2');
  await page.locator('#preprocess-before [data-removed-path="events[1].source_line"]').waitFor();
  assert.equal(await page.locator('#preprocess-before [data-removed-path="events[0].source_line"]').count(), 0);
  assert.equal(await page.locator('#preprocess-after [data-replaced-path="events[1].tool_calls[0].tool_call_id"]').textContent(), '"tool_call_id": "call-0002"');
  await page.locator('#preprocess-event').selectOption(before.event_id);
  await page.waitForFunction(id => JSON.parse(document.querySelector('#preprocess-after').textContent).event_id === id, before.event_id);
  await page.locator('.preprocess-id-mapping summary').click();
  const output = path.join(root, 'runs/browser-checks');
  fs.mkdirSync(output, { recursive: true });
  await page.screenshot({ path: path.join(output, 'preprocess-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.locator('.preprocess-before').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(output, 'preprocess-mobile.png') });
  await page.locator('.preprocess-id-mapping').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(output, 'preprocess-mobile-mapping.png') });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: '基于此结果创建切分', exact: true }).click();
  const sourceId = experimentUrl.split('/#experiment/')[1];
  assert.equal(await page.locator('#split-preprocess-source').inputValue(), sourceId);
  await page.locator('#split-trajectory-picker input').first().waitFor({ state: 'attached' });
  await page.locator('#new-split-form [name=title]').fill('来自预处理的切分');
  for (const [key, value] of Object.entries({ max_window_events:2, overlap_events:1, max_previous_summary_tokens:0, max_future_summary_tokens:0 })) {
    await page.locator(`[name=${key}]`).fill(String(value));
  }
  await page.locator('#split-preview[data-window-count="2"]').waitFor();
  await page.getByRole('button', { name: '创建切分实验草稿', exact: true }).click();
  await page.getByRole('button', { name: '开始运行', exact: true }).click();
  await page.getByRole('button', { name: '基于此切分发现谓词', exact: true }).waitFor();
  assert((await page.locator('#main').textContent()).includes('工具输出去重 · 对照实验'));
  assert.deepEqual(errors, []);
  console.log('PASS: optional short call IDs, red deletions/yellow replacements on both sides, mapping review, exact JSON text, run/reload, event/full trajectory selection, desktop/mobile layout and downstream splitting.');
}
run().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); fixture.kill('SIGINT'); });
